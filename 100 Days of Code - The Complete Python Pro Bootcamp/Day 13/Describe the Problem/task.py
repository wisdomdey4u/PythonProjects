def my_function():
    for i in range(1, 21):
        if i == 20:
            print("You got it")

my_function()

# describe the Problem - Write your answers as comments:
# 1. What is for loop doing?
# 2. What is the function amount to print "you got it"?
# 3. What are your assumptions about the value of i?

# Answer
# 1. The for loop iterates through a sequence of numbers starting from 1 up to (but not including) 20.
# 2. The function will print "you got it" exactly 0 times (it will never print).
# 3. The value of i will start at 1 and increase by 1 each loop, reaching a maximum value of 19.
